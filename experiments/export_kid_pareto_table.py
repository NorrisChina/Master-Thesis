#!/usr/bin/env python3
"""Export Pareto-nondominated K-ID configurations to a LaTeX table.

Reads the CSV produced by experiments/kid_parameter_sweep.py and outputs a
thesis-ready table listing the Pareto-nondominated (risk vs speedup) points.

We match the plotting definition:
- x = overall risk P(unsafe ∩ accept) = miss_count / ticks
- y = speedup
- Pareto objective: minimize x, maximize y

Example:
  python3 experiments/export_kid_pareto_table.py \
    --gaussian-csv experiments/results/kid_sweep_gaussian_both_ndata4001.csv \
    --uniform-csv experiments/results/kid_sweep_uniform_both_ndata4001.csv \
    --out-tex thesis_report/tables/generated/kid_pareto_points_ndata4001.tex
"""

from __future__ import annotations

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Sequence, Tuple


@dataclass(frozen=True)
class Row:
    model: str
    system: str
    n_ver_bits: int
    k_radius: int
    speedup: float
    ticks: int
    miss_count: int

    @property
    def overall_risk(self) -> float:
        return (self.miss_count / self.ticks) if self.ticks else 0.0


def pareto_nondominated(points: List[Tuple[float, float]]) -> List[bool]:
    """Return a boolean mask indicating Pareto-nondominated points.

    We want: minimize x (risk), maximize y (speedup).
    """
    mask = [True] * len(points)
    for i, (xi, yi) in enumerate(points):
        if not mask[i]:
            continue
        for j, (xj, yj) in enumerate(points):
            if i == j:
                continue
            if (xj <= xi and yj >= yi) and (xj < xi or yj > yi):
                mask[i] = False
                break
    return mask


def load_rows(csv_path: Path, *, model: str) -> List[Row]:
    with csv_path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows: List[Row] = []
        for r in reader:
            rows.append(
                Row(
                    model=model,
                    system=str(r.get("system", "sha256_trunc")),
                    n_ver_bits=int(r["n_ver_bits"]),
                    k_radius=int(r["k_radius"]),
                    speedup=float(r["speedup"]),
                    ticks=int(r["ticks"]),
                    miss_count=int(r["miss_count"]),
                )
            )
    return rows


def pareto_points(rows: List[Row], *, eps: float = 1e-12) -> List[Row]:
    pts = [(max(r.overall_risk, eps), r.speedup) for r in rows]
    nd = pareto_nondominated(pts)
    keep = [r for r, is_nd in zip(rows, nd) if is_nd]
    keep.sort(key=lambda r: (r.overall_risk, -r.speedup, r.k_radius, r.n_ver_bits))
    return keep


def fmt_risk(x: float) -> str:
    if x == 0.0:
        return "0"
    # Use scientific notation for very small values.
    if x < 1e-3:
        return f"{x:.1e}"
    return f"{x:.4f}"


def build_table(gaussian: Dict[str, List[Row]], uniform: Dict[str, List[Row]]) -> str:
    lines: List[str] = []
    lines.append("% Auto-generated by experiments/export_kid_pareto_table.py")
    lines.append(r"\begin{table}[!t]")
    lines.append(r"\centering")
    lines.append(
        r"\caption{Pareto-nondominated \gls{kid} configurations under Gaussian and variance-matched Uniform models ($n_{data}=4001$ bits, $B=1$ Mbps). Overall risk is empirical $P(\mathrm{unsafe}\cap\mathrm{accept})$ per tick.}"
    )
    lines.append(r"\label{tab:kid_pareto_points}")
    lines.append(r"\begin{tabular}{l l r r r r}")
    lines.append(r"\toprule")
    lines.append(r"Model & System & $K$ & $n_{ver}$ & Overall risk & Speedup ($\times$) \\")
    lines.append(r"\midrule")

    def tex_escape(s: str) -> str:
        # Minimal escaping for this table.
        return s.replace("_", r"\_")

    def add_block(model_name: str, by_system: Dict[str, List[Row]]) -> None:
        systems_sorted = sorted(by_system.keys())
        row_end = r"\\"  # end-of-row for LaTeX tabular
        for system in systems_sorted:
            for idx, r in enumerate(by_system[system]):
                model_cell = model_name if (system == systems_sorted[0] and idx == 0) else ""
                system_cell = tex_escape(system) if idx == 0 else ""
                lines.append(
                    f"{model_cell} & {system_cell} & {r.k_radius} & {r.n_ver_bits} & {fmt_risk(r.overall_risk)} & {r.speedup:.2f} {row_end}"
                )
            lines.append(r"\addlinespace")

    add_block("Gaussian", gaussian)
    lines.append(r"\midrule")
    add_block("Uniform", uniform)

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")
    return "\n".join(lines)


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Export Pareto-nondominated K-ID points to LaTeX")
    p.add_argument("--gaussian-csv", type=Path, required=True)
    p.add_argument("--uniform-csv", type=Path, required=True)
    p.add_argument("--out-tex", type=Path, required=True)
    return p.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)

    repo_root = Path(__file__).resolve().parents[1]
    g_csv = args.gaussian_csv if args.gaussian_csv.is_absolute() else repo_root / args.gaussian_csv
    u_csv = args.uniform_csv if args.uniform_csv.is_absolute() else repo_root / args.uniform_csv
    out_tex = args.out_tex if args.out_tex.is_absolute() else repo_root / args.out_tex

    g_rows = load_rows(g_csv, model="Gaussian")
    u_rows = load_rows(u_csv, model="Uniform")

    def group(rows: List[Row]) -> Dict[str, List[Row]]:
        by: Dict[str, List[Row]] = {}
        for r in rows:
            by.setdefault(r.system, []).append(r)
        return {sys: pareto_points(rs) for sys, rs in by.items()}

    tex = build_table(group(g_rows), group(u_rows))
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text(tex, encoding="utf-8")
    print(f"Wrote: {out_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
